
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

from app.config import settings


def get_db_connection():
    """Open a PostgreSQL connection using the configured Neon URL."""
    settings.validate_database()

    return psycopg.connect(
        settings.DATABASE_URL,
        connect_timeout=10,
        row_factory=dict_row,
        application_name="solveease-intentforge",
    )


@contextmanager
def db_connection():
    """Commit successful operations and roll back failures."""
    conn = get_db_connection()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    """Create all application tables and indexes in PostgreSQL."""
    with db_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS mega_intent_firehose (
                task_hash TEXT PRIMARY KEY,
                task_id TEXT NOT NULL UNIQUE,
                timestamp TEXT NOT NULL,
                source TEXT NOT NULL,
                task_category TEXT NOT NULL,
                raw_signal TEXT NOT NULL,
                micro_price INTEGER NOT NULL
                    CHECK (micro_price BETWEEN 100 AND 500),
                action TEXT NOT NULL DEFAULT 'pending'
                    CHECK (action IN (
                        'pending', 'published', 'sold', 'archived'
                    ))
            );
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_mega_price
            ON mega_intent_firehose(micro_price);
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_mega_timestamp
            ON mega_intent_firehose(timestamp);
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_mega_category_action
            ON mega_intent_firehose(task_category, action);
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS verified_payments (
                reference TEXT PRIMARY KEY,
                task_id TEXT NOT NULL,
                customer_email TEXT NOT NULL,
                tier TEXT NOT NULL,
                amount INTEGER NOT NULL,
                currency TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN (
                        'pending', 'processing', 'sent', 'failed'
                    )),
                created_at BIGINT NOT NULL,
                updated_at BIGINT NOT NULL
            );
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_payments_status
            ON verified_payments(status, updated_at);
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS fulfillment_jobs (
                job_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                task_id TEXT NOT NULL,
                purchase_reference TEXT NOT NULL UNIQUE,
                recipient_email TEXT NOT NULL,
                tier TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN (
                        'pending', 'processing', 'retry', 'sent', 'dead'
                    )),
                attempts INTEGER NOT NULL DEFAULT 0,
                next_attempt_at TIMESTAMPTZ NOT NULL,
                locked_at TIMESTAMPTZ,
                last_error TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            );
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_fulfillment_due
            ON fulfillment_jobs(status, next_attempt_at);
        """)
